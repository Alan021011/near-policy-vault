// Generates golden vectors for the EIP-1559 signing hash using viem.
// The Rust test in contract/tests/golden_vectors.rs must reproduce every line byte for byte.
//
// Run: node gen-vectors.mjs
// Output: ../vectors/eip1559_signing_hash.tsv (tab separated, one case per line)

import { serializeTransaction, keccak256 } from 'viem';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '..', 'vectors', 'eip1559_signing_hash.tsv');

const addrA = '0x1111111111111111111111111111111111111111';
const addrB = '0xdeadbeefdeadbeefdeadbeefdeadbeefdeadbeef';
const spender = 'bb'.repeat(20);
const maxUint = 'ff'.repeat(32);
const approveCalldata =
  '0x095ea7b3' + '00'.repeat(12) + spender + maxUint; // approve(spender, 2^256-1)
const bytesOf = (n, byte) => '0x' + byte.repeat(n);

const base = {
  chainId: 11155111,
  nonce: 0,
  maxPriorityFeePerGas: 1_000_000_000n,
  maxFeePerGas: 20_000_000_000n,
  gas: 21000n,
  to: addrA,
  value: 1_000_000_000_000_000n,
  data: '0x',
};

const cases = [
  ['simple_eth_transfer', {}],
  ['zero_value', { value: 0n }],
  ['nonce_127', { nonce: 127 }],
  ['nonce_128', { nonce: 128 }],
  ['nonce_255', { nonce: 255 }],
  ['nonce_256', { nonce: 256 }],
  ['nonce_65536', { nonce: 65536 }],
  ['large_fees', { maxPriorityFeePerGas: 18446744073709551621n, maxFeePerGas: 340282366920938463463374607431768211455n }],
  ['value_2_pow_100', { value: 2n ** 100n }],
  ['gas_1m', { gas: 1_000_000n }],
  ['chain_1', { chainId: 1 }],
  ['chain_hoodi', { chainId: 560048 }],
  ['other_recipient', { to: addrB }],
  ['data_1_byte_low', { data: '0x01' }],
  ['data_1_byte_high', { data: '0x80' }],
  ['data_55_bytes', { data: bytesOf(55, 'ab') }],
  ['data_56_bytes', { data: bytesOf(56, 'ab') }],
  ['data_300_bytes', { data: bytesOf(300, 'cd') }],
  ['approve_unlimited_68_bytes', { data: approveCalldata }],
];

const lines = [
  '# Golden vectors for the EIP-1559 signing hash, generated by scripts/gen-vectors.mjs with viem.',
  '# columns: name, chain_id, nonce, max_priority_fee, max_fee, gas_limit, to, value, data, serialized_unsigned, signing_hash',
];

for (const [name, patch] of cases) {
  const tx = { ...base, ...patch };
  const serialized = serializeTransaction({ type: 'eip1559', accessList: [], ...tx });
  const hash = keccak256(serialized);
  lines.push(
    [
      name,
      tx.chainId,
      tx.nonce,
      tx.maxPriorityFeePerGas,
      tx.maxFeePerGas,
      tx.gas,
      tx.to,
      tx.value,
      tx.data,
      serialized,
      hash,
    ].join('\t'),
  );
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${cases.length} vectors to ${out}`);
